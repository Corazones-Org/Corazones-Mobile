create table profile_outing_types (
  user_id uuid not null references profiles(user_id) on delete cascade,
  outing_type_id smallint not null references outing_types(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (user_id, outing_type_id)
);

-- Only active outing types can be added. There is no maximum: unlike interests, a person can be
-- up for many kinds of plans.
create or replace function check_profile_outing_type()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if not exists (select 1 from outing_types where id = new.outing_type_id and active) then
    raise exception 'outing type % is not active', new.outing_type_id using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger profile_outing_types_check
  before insert on profile_outing_types
  for each row
  execute function check_profile_outing_type();

alter table outing_types enable row level security;
alter table profile_outing_types enable row level security;

create policy "outing_types_select_authenticated"
  on outing_types for select
  to authenticated
  using (true);

-- Same visibility as the rest of the profile (0017): the owner, or someone in the same slot today.
create policy "profile_outing_types_select_visible"
  on profile_outing_types for select
  to authenticated
  using (can_view_profile(user_id));

create policy "profile_outing_types_insert_own"
  on profile_outing_types for insert
  to authenticated
  with check (user_id = auth.uid());

create policy "profile_outing_types_delete_own"
  on profile_outing_types for delete
  to authenticated
  using (user_id = auth.uid());
