-- Outing types ("Tipo de salida"): the kinds of plan a person is up for. Same shape as interests
-- (0016): the database is the source of truth, including the display labels, so an admin can add or
-- retire a type without an app release. Retire with `active = false`, never delete a row that
-- profiles reference.
-- Meant for matching between profiles later (sorting, "you both want ..." badges), so the `code`
-- is the stable value to compare; labels are only for display.
create table outing_types (
  id smallint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z0-9_]+$'),
  labels jsonb not null check (jsonb_typeof(labels) = 'object' and labels ? 'es'),
  active boolean not null default true,
  sort_order smallint not null default 0
);

