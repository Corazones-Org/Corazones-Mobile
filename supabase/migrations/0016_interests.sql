create table profile_interests (
  user_id uuid not null references profiles(user_id) on delete cascade,
  interest_id smallint not null references interests(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (user_id, interest_id)
);

-- Max 10 interests per profile, and only active ones can be added.
create or replace function check_profile_interest()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $$
begin
  if not exists (select 1 from interests where id = new.interest_id and active) then
    raise exception 'interest % is not active', new.interest_id using errcode = 'check_violation';
  end if;
  if (select count(*) from profile_interests where user_id = new.user_id) >= 10 then
    raise exception 'a profile can have at most 10 interests' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger profile_interests_check
  before insert on profile_interests
  for each row
  execute function check_profile_interest();

alter table interests enable row level security;
alter table profile_interests enable row level security;

create policy "interests_select_authenticated"
  on interests for select
  to authenticated
  using (true);
