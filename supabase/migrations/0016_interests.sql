-- Interests catalog: the database is the source of truth, including the
-- display labels (unlike the fixed catalogs), so an admin can add or retire
-- an interest without an app release. Retire with `active = false`, never
-- delete a row that profiles reference.
create table interests (
  id smallint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z0-9_]+$'),
  labels jsonb not null check (jsonb_typeof(labels) = 'object' and labels ? 'es'),
  active boolean not null default true,
  sort_order smallint not null default 0
);

